using SpaceSim.Localization;
using System;
using System.Collections.Generic;
using SpaceSim.Physics;
using SpaceSim.Planets;
using SpaceSim.Units;

namespace SpaceSim.Flight
{
    /// <summary>
    /// Text of the in-game Flight Manual. Worked examples are computed live from the current planet's data,
    /// so they stay correct when the planet's mass, radius or atmosphere is changed.
    /// Uses IMGUI rich-text tags (&lt;b&gt;, &lt;i&gt;, &lt;color&gt;).
    /// </summary>
    public static class FlightManualContent
    {
        public readonly struct Section
        {
            public Section(string title, string body)
            {
                Title = title;
                Body = body;
            }

            public string Title { get; }
            public string Body { get; }
        }

        const string F = "<color=#9fd8ff><b>";
        const string EF = "</b></color>";
        const string Warn = "<color=#ffc36b><b>";
        const string EW = "</b></color>";

        static string N(double v, int d) => UnitFormatter.Number(v, d);
        static string Km(double m) => UnitFormatter.Number(m / 1000.0, 1) + Loc.T(" км");

        public static List<Section> Build(PlanetModel planet, double launchLatitudeDeg)
        {
            double mu = planet.GravitationalParameter;
            double R = planet.Radius;
            double g0 = mu / (R * R);
            double r200 = R + 200000.0, r400 = R + 400000.0;
            double vc200 = OrbitalMechanics.CircularVelocity(mu, r200);
            double vc400 = OrbitalMechanics.CircularVelocity(mu, r400);
            double ve0 = OrbitalMechanics.EscapeVelocity(mu, R);
            double ve400 = OrbitalMechanics.EscapeVelocity(mu, r400);
            double T400 = OrbitalMechanics.CircularPeriod(mu, r400);
            double g400 = mu / (r400 * r400);
            double lat = launchLatitudeDeg * Math.PI / 180.0;
            double vRot = planet.Rotation.AngularSpeed * R * Math.Cos(lat);
            double boundary = planet.SpaceBoundaryAltitude;
            double vUp100 = Math.Sqrt(2.0 * mu * (1.0 / R - 1.0 / (R + boundary)));
            var atm = planet.Atmosphere;
            bool hasAir = atm.ReferenceDensity > 0.0;
            double rho0 = atm.ReferenceDensity;
            double H = hasAir && atm is ExponentialAtmosphere ea ? ea.ScaleHeight : double.NaN;
            double vt = hasAir ? AtmosphericDrag.TerminalVelocity(500.0, g0, rho0, 1.05, Math.PI) : double.NaN;

            var s = new List<Section>();

            s.Add(new Section(Loc.T("1. Единицы и обозначения"),
                Loc.T("Все расчёты симулятора ведутся в системе СИ; интерфейс только округляет числа.\n\n") +
                Loc.T("• расстояние — метры (м); время — секунды (с); масса — килограммы (кг)\n") +
                Loc.T("• скорость — м/с; ускорение — м/с²; сила — ньютоны (Н = кг·м/с²)\n") +
                Loc.T("• энергия — джоули (Дж); удельная энергия — Дж/кг = м²/с²\n") +
                Loc.T("• давление — паскали (Па); плотность — кг/м³; температура — кельвины (К)\n\n") +
                Loc.T("<b>Обозначения</b>\n") +
                Loc.T("G — гравитационная постоянная = 6.67430·10⁻¹¹ м³/(кг·с²)\n") +
                Loc.T("M — масса планеты; μ = G·M — гравитационный параметр [м³/с²]\n") +
                Loc.T("R — средний (опорный) радиус планеты; r — расстояние от ЦЕНТРА планеты до аппарата\n") +
                Loc.T("h = r − R — высота над опорной сферой; v — модуль скорости; v_r — её радиальная (вертикальная) часть\n\n") +
                Loc.T("Для текущей планеты: μ = ") + UnitFormatter.Scientific(mu, 6) + Loc.T(" м³/с², R = ") + N(R, 0) + Loc.T(" м, g(R) = ") + N(g0, 3) + Loc.T(" м/с².\n\n") +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" смешивать км и м в одной формуле. Переводите всё в метры до вычислений.")));

            s.Add(new Section(Loc.T("2. Высота, радиус орбиты, расстояние от центра"),
                Loc.T("Формулы гравитации и орбит работают с расстоянием от центра ") + F + "r" + EF + Loc.T(", а не с высотой.\n\n") +
                F + "r = R + h" + EF + "\n\n" +
                Loc.T("Приборы показывают три величины:\n") +
                Loc.T("• <b>Высота над поверхностью</b> — до реального рельефа под аппаратом (горы, океан). Нужна для посадки.\n") +
                Loc.T("• <b>Высота над R</b> — над опорной сферой радиуса R. Так задаются орбиты и граница космоса.\n") +
                Loc.T("• <b>От центра (r)</b> — то, что подставляется в формулы.\n\n") +
                Loc.T("<b>Пример.</b> Орбита на высоте 400 км: r = ") + N(R, 0) + " + 400 000 = " + N(r400, 0) + Loc.T(" м.\n\n") +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" подставить h = 400 000 м вместо r в √(μ/r). Получится ")
                + N(Math.Sqrt(mu / 400000.0), 0) + Loc.T(" м/с вместо ") + N(vc400, 0) + Loc.T(" м/с.")));

            s.Add(new Section(Loc.T("3. Скорость и ускорение"),
                Loc.T("<b>Скорость</b> — как быстро и куда меняется положение (вектор, м/с). <b>Ускорение</b> — как быстро меняется сама скорость (вектор, м/с²).\n") +
                Loc.T("Гравитация задаёт ускорение, а не скорость: на орбите тело всё время ускоряется к центру, но модуль скорости почти не меняется — меняется её направление.\n\n") +
                Loc.T("<b>Три скорости на приборах</b>\n") +
                Loc.T("• инерциальная — относительно звёзд; именно она входит в орбитальные формулы;\n") +
                Loc.T("• относительно поверхности — v − ω×r, то, что видит наблюдатель на земле;\n") +
                Loc.T("• относительно воздуха — для сопротивления (при отсутствии ветра совпадает с предыдущей).\n\n") +
                Loc.T("Покоящийся на стартовой площадке аппарат (широта ") + N(launchLatitudeDeg, 2) + Loc.T("°) уже движется инерциально на восток со скоростью ") +
                F + "ω·R·cos φ ≈ " + N(vRot, 1) + Loc.T(" м/с") + EF + Loc.T(". Старт на восток экономит эту скорость, на запад — добавляет её к требуемой.\n\n") +
                Loc.T("<b>Перегрузка</b> (акселерометр) — ускорение без учёта гравитации. На площадке ≈ 1 g₀, в свободном полёте (в том числе на орбите) = 0, хотя g(r) ≠ 0.\n\n") +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" «на орбите нет гравитации». На 400 км g = ") + N(g400, 2) + Loc.T(" м/с² — ") + N(100.0 * g400 / g0, 0) + Loc.T("% от поверхностной. Невесомость — это свободное падение.")));

            s.Add(new Section(Loc.T("4. Закон всемирного тяготения"),
                F + "F = G·M·m / r²" + EF + "     " + F + "g(r) = μ / r²" + EF + "     " + F + "a⃗ = −μ·r⃗ / |r⃗|³" + EF + "\n\n" +
                Loc.T("r⃗ направлен от центра планеты к аппарату, знак «−» означает притяжение к центру. Масса аппарата m в ускорение не входит — все тела падают одинаково.\n\n") +
                Loc.T("<b>Когда применимо:</b> сферически-симметричная планета, точка вне её. Не учитываются сплюснутость (J2), неоднородности масс, приливы, другие тела.\n\n") +
                Loc.T("<b>Пример.</b> g(R) = ") + UnitFormatter.Scientific(mu, 4) + " / " + N(R, 0) + "² = " + N(g0, 3) + Loc.T(" м/с²;  g(R+400 км) = ") + N(g400, 3) + Loc.T(" м/с².\n") +
                Loc.T("(Привычные 9.81 м/с² на Земле включают центробежный эффект вращения и сплюснутость; чистая гравитация на среднем радиусе ≈ 9.82.)\n\n") +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" считать g постоянным на любой высоте. Используйте g(r) = μ/r².")));

            s.Add(new Section(Loc.T("5. Почему орбите нужна горизонтальная скорость"),
                Loc.T("Орбита — это непрерывное падение, при котором аппарат «промахивается» мимо планеты. За время падения он успевает сместиться вбок настолько, что поверхность изгибается вниз вместе с ним.\n\n") +
                Loc.T("• Вертикальная скорость только поднимает аппарат: без горизонтальной составляющей он упадёт обратно по той же линии.\n") +
                Loc.T("• Чтобы подняться на ") + Km(boundary) + Loc.T(" вертикально (без атмосферы), нужно около ") + F + N(vUp100, 0) + Loc.T(" м/с") + EF + Loc.T(" — из ε = const: v² = 2μ(1/R − 1/(R+h)).\n") +
                Loc.T("• Чтобы на той же высоте не упасть, нужно около ") + F + N(OrbitalMechanics.CircularVelocity(mu, R + boundary), 0) + Loc.T(" м/с") + EF + Loc.T(" горизонтально.\n\n") +
                Loc.T("Радиальная скорость v_r на приборах показывает, сближаетесь ли вы с центром (v_r < 0) или удаляетесь (v_r > 0). На круговой орбите v_r ≈ 0.\n\n") +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" набрать высоту и ждать, что аппарат «останется в космосе». Попробуйте в инструменте начальных условий (I): h = 150 000, все скорости 0 — и посмотрите, что произойдёт.")));

            s.Add(new Section(Loc.T("6. Круговая орбитальная скорость"),
                F + Loc.T("v_круг = √(μ / r)") + EF + "\n\n" +
                Loc.T("Получается из равенства центростремительного ускорения v²/r и гравитационного μ/r².\n\n") +
                Loc.T("<b>Пример.</b> h = 200 км: r = ") + N(r200, 0) + Loc.T(" м, v = √(") + UnitFormatter.Scientific(mu, 4) + " / " + N(r200, 0) + ") = " + F + N(vc200, 1) + Loc.T(" м/с") + EF + ".\n" +
                Loc.T("h = 400 км: v = ") + N(vc400, 1) + Loc.T(" м/с — выше орбита, ниже скорость.\n\n") +
                Loc.T("<b>Предположения:</b> двухтельная задача, без атмосферы; скорость инерциальная и направлена строго горизонтально.\n\n") +
                Warn + Loc.T("Частые ошибки:") + EW + Loc.T(" (1) подставить высоту вместо r; (2) задать скорость «относительно поверхности» и забыть, что инерциальная скорость будет больше на ω·R·cos φ при движении на восток; (3) добавить вертикальную составляющую — орбита станет эллиптической.")));

            s.Add(new Section(Loc.T("7. Вторая космическая (скорость убегания)"),
                F + Loc.T("v_уход = √(2μ / r) = √2 · v_круг") + EF + "\n\n" +
                Loc.T("Минимальная скорость, при которой ε ≥ 0 и аппарат не вернётся (в идеальной модели — без атмосферы, без вращения, без других тел). Направление не важно, если траектория не пересекает планету.\n\n") +
                Loc.T("<b>Пример.</b> С поверхности: ") + N(ve0, 0) + Loc.T(" м/с; с высоты 400 км: ") + N(ve400, 0) + Loc.T(" м/с.\n\n") +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" считать её скоростью, которую нужно набрать у поверхности в реальной атмосфере: сопротивление и потери на гравитацию требуют больше.")));

            s.Add(new Section(Loc.T("8. Удельная орбитальная энергия"),
                F + "ε = v²/2 − μ/r" + EF + Loc.T("    [Дж/кг]\n\n") +
                Loc.T("Сумма кинетической и потенциальной энергии на килограмм. Без сопротивления и двигателей ε постоянна — это хороший контроль точности симуляции.\n") +
                Loc.T("• ε < 0 — движение связанное (эллипс), аппарат не может уйти бесконечно далеко;\n") +
                Loc.T("• ε = 0 — параболическая граница;\n") +
                Loc.T("• ε > 0 — гипербола, уход от планеты.\n") +
                Loc.T("Для круговой орбиты ε = −μ/(2r); на 400 км: ") + N(-mu / (2.0 * r400), 0) + Loc.T(" Дж/кг.\n\n") +
                Warn + Loc.T("Важно:") + EW + Loc.T(" ε < 0 НЕ означает устойчивую орбиту. Тело, неподвижно зависшее на 100 км, имеет ε = ") + N(-mu / (R + boundary), 0) +
                Loc.T(" Дж/кг < 0 — и падает. Нужно ещё, чтобы перицентр r_p = h²/(μ(1+e)) был выше поверхности и плотной атмосферы.")));

            s.Add(new Section(Loc.T("9. Период круговой орбиты"),
                F + "T = 2π · √(r³ / μ)" + EF + "\n\n" +
                Loc.T("Для эллипса вместо r подставляется большая полуось a = −μ/(2ε) (третий закон Кеплера).\n\n") +
                Loc.T("<b>Пример.</b> h = 400 км: T = 2π·√(") + N(r400, 0) + "³ / " + UnitFormatter.Scientific(mu, 4) + ") = " + F + N(T400, 0) + Loc.T(" с ≈ ") + N(T400 / 60.0, 1) + Loc.T(" мин") + EF + ".\n\n" +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" забыть возвести r в куб или использовать километры с μ в м³/с².")));

            string airText = hasAir
                ? Loc.T("Модель плотности: ") + F + "ρ(h) = ρ₀ · e^(−h/H)" + EF + (double.IsNaN(H) ? Loc.T(" (сейчас — табличная модель)") : ", ρ₀ = " + N(rho0, 3) + Loc.T(" кг/м³, H = ") + N(H, 0) + Loc.T(" м")) + ".\n" +
                  "ρ(0) = " + UnitFormatter.Density(atm.Density(0)) + Loc.T("; ρ(10 км) = ") + UnitFormatter.Density(atm.Density(10000)) +
                  Loc.T("; ρ(50 км) = ") + UnitFormatter.Density(atm.Density(50000)) + Loc.T("; ρ(100 км) = ") + UnitFormatter.Density(atm.Density(100000)) +
                  Loc.T("; ρ(200 км) = ") + UnitFormatter.Density(atm.Density(200000)) + ".\n" +
                  Loc.T("Плотность убывает плавно и не обращается в ноль ни на какой высоте.\n\n") +
                  Loc.T("<b>Сопротивление</b>: ") + F + "F = ½ · ρ · v_rel² · Cd · A" + EF + Loc.T(", направлено против скорости относительно воздуха.\n") +
                  Loc.T("Скоростной напор q = ½ρv² [Па] показан на приборах.\n") +
                  Loc.T("Предельная скорость падения: ") + F + "v_t = √(2mg / (ρ·Cd·A))" + EF + Loc.T(". Для тестового зонда (m = 500 кг, Cd = 1.05, A = π м²) у поверхности: ≈ ") + N(vt, 0) + Loc.T(" м/с.\n\n") +
                  Loc.T("<b>Не учитывается:</b> подъёмная сила, зависимость Cd от числа Маха, нагрев, ветер, суточные изменения атмосферы.")
                : Loc.T("У этой планеты нет атмосферы: сопротивления нет, орбиты возможны на любой высоте выше рельефа.");
            s.Add(new Section(Loc.T("10. Атмосфера и сопротивление"), airText + "\n\n" +
                Warn + Loc.T("Частая ошибка:") + EW + Loc.T(" брать в формулу сопротивления инерциальную скорость. Воздух вращается вместе с планетой: на площадке инерциальная скорость ≈ ") +
                N(vRot, 0) + Loc.T(" м/с, а сопротивления нет.")));

            s.Add(new Section(Loc.T("11. Почему 100 км — ещё не орбита"),
                Loc.T("Высота ") + Km(boundary) + Loc.T(" — <b>условная</b> граница космоса (линия Кармана). Это соглашение, а не физический край: атмосфера продолжается выше, просто становится очень разреженной.\n\n") +
                Loc.T("Достичь высоты и выйти на орбиту — разные задачи:\n") +
                Loc.T("• для высоты нужна энергия на подъём (≈ ") + N(vUp100, 0) + Loc.T(" м/с вертикально);\n") +
                Loc.T("• для орбиты нужна горизонтальная скорость ≈ ") + N(OrbitalMechanics.CircularVelocity(mu, R + boundary), 0) + Loc.T(" м/с — в несколько раз больше;\n") +
                Loc.T("• на высоте ~100–140 км сопротивление ещё заметно: орбита с таким перицентром быстро снижается. Симулятор называет орбиту устойчивой, только если ε < 0 и перицентр выше порога (по умолчанию 140 км).\n\n") +
                Loc.T("Поэтому интерфейс сообщает о пересечении границы, но фазу «Орбитальный полёт» показывает только по орбитальным критериям.")));

            s.Add(new Section(Loc.T("12. Как пользоваться приборами при планировании"),
                Loc.T("1. Выберите целевую высоту h и посчитайте r = R + h.\n") +
                Loc.T("2. Посчитайте v_круг = √(μ/r) и период T.\n") +
                Loc.T("3. Учтите вращение: если задаёте скорость относительно поверхности на восток, вычтите ω·R·cos φ (") + N(vRot, 1) + Loc.T(" м/с на площадке).\n") +
                Loc.T("4. Откройте начальные условия (I), задайте h и горизонтальную скорость, вертикальную = 0. Примените.\n") +
                Loc.T("5. Проверьте: ε должна быть ≈ −μ/(2r), v_r должна колебаться около нуля, высота — оставаться почти постоянной.\n") +
                Loc.T("6. Сравните со значениями анализа орбиты (O). Расхождение — повод найти ошибку в расчёте.\n") +
                Loc.T("7. Попробуйте ускорение времени (.) — физический шаг не меняется, результаты не зависят от FPS.\n\n") +
                Loc.T("<b>Эксперименты:</b> скорость на 5% меньше круговой (эллипс с перицентром ниже), на 5% больше; запуск с v = v_уход; орбита на 110 км со включённым сопротивлением.")));

            double vRotEq = planet.Rotation.AngularSpeed * R;
            s.Add(new Section(Loc.T("13. Ракета: тяга, топливо, выход на орбиту"),
                Loc.T("Ракета многоступенчатая; управляете ею только вы — автопилота нет.\n\n") +
                Loc.T("• массовый расход ") + F + "ṁ = F_vac / (I_sp,vac · g₀)" + EF + Loc.T(" [кг/с], g₀ = 9.80665 м/с² — единица, а не местная гравитация;\n") +
                Loc.T("• тяга ") + F + "F = ṁ · g₀ · I_sp(p)" + EF + Loc.T(": у поверхности I_sp меньше (давление на срезе сопла), поэтому тяга растёт с высотой;\n") +
                Loc.T("• масса m(t) = m₀ − ṁ·t; ускорение от тяги F/m растёт по мере выгорания топлива;\n") +
                Loc.T("• запас скорости — формула Циолковского ") + F + Loc.T("Δv = I_sp · g₀ · ln(m₀ / m_к)") + EF + Loc.T(", суммируется по ступеням;\n") +
                Loc.T("• старт возможен, только если тяга/вес = F/(m·g) > 1.\n\n") +
                Loc.T("<b>Как выйти на орбиту (вы решаете сами):</b>\n") +
                Loc.T("1. ЗАПУСК вертикально. 2. Через ~10–20 с начните плавно наклонять (W) на восток (курс 90°) — так используется вращение планеты (") + N(vRotEq, 0) + Loc.T(" м/с на экваторе).\n") +
                Loc.T("3. Следите за скоростным напором q — слишком резкий наклон в плотном воздухе даёт большие потери.\n") +
                Loc.T("4. Выше атмосферы нужна горизонтальная скорость ≈ √(μ/r) (") + N(vc200, 0) + Loc.T(" м/с на 200 км). Смотрите на ε и v_r.\n") +
                Loc.T("5. Пустую ступень отделяйте (Пробел) и включайте следующую (Enter).\n\n") +
